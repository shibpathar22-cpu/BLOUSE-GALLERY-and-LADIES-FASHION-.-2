// Generates dynamic dates relative to current date (e.g. today 2026-10-28)
const getTodayStr = () => {
  const d = new Date();
  return d.toISOString().split('T')[0];
};

const getOffsetDateStr = (daysOffset: number) => {
  const d = new Date();
  d.setDate(d.getDate() + daysOffset);
  return d.toISOString().split('T')[0];
};

